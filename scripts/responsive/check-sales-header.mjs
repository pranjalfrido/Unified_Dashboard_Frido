// Sales phone header (MobilePageHeader): channel chips switch the channel, sub-tabs switch the view
// (Amazon, D2C, Offline), "⋯" lists the desktop Export options, the desktop tab bar / filter bar are
// hidden, the header stays pinned, no horizontal overflow.
// Usage: node scripts/responsive/check-sales-header.mjs [viewportName]   (RESPONSIVE_ENGINE=webkit ok)
import { launch, openPage, VIEWPORTS, ENGINE, waitSettled } from './lib.mjs'
const vp = VIEWPORTS.find(v => v.name === (process.argv[2] || 'iphone14-390x844'))
const { browser, ctx } = await launch(vp)
const page = await ctx.newPage()
let fail = 0
const check = (name, ok, extra = '') => { if (!ok) fail++; console.log(`${ok ? 'PASS' : 'FAIL'} ${name}${extra ? ' - ' + extra : ''}`) }
const hdr = page.locator('.topnav.m-header')
await openPage(page, '/sales/all')
check('header has title, channel chips, filter icon', await hdr.isVisible() && (await hdr.innerText()).includes('Sales') && (await hdr.getByRole('button', { name: 'D2C', exact: true }).count()) === 1 && (await hdr.locator('.ov-filter-btn').count()) === 1)
check('desktop tab bar and filter bar hidden', !(await page.locator('.sales-tabs').isVisible()) && !(await page.locator('.fbar').isVisible()))
await hdr.getByRole('button', { name: 'Amazon', exact: true }).click(); await waitSettled(page)
check('chip opens Amazon', page.url().includes('/sales/amazon') && (await hdr.innerText()).includes('Amazon'), page.url().replace(/^.*\/sales/, '/sales'))
await hdr.getByRole('tab', { name: 'Seller Central' }).click(); await page.waitForTimeout(800)
check('sub-tab switches to Seller Central', page.url().includes('seller_central') && (await hdr.getByRole('tab', { name: 'Seller Central' }).getAttribute('aria-selected')) === 'true', page.url().replace(/^.*\/sales/, '/sales'))
await hdr.getByRole('button', { name: 'More actions' }).click(); await page.waitForTimeout(400)
const sheet = page.getByRole('dialog')
const txt = await sheet.innerText()
check('"⋯" lists the Export options', /Category SKU/.test(txt) && /Top States & Cities/.test(txt) && /Full Export/.test(txt), txt.replace(/\s+/g, ' ').slice(0, 80))
await page.goBack(); await page.waitForTimeout(300)
check('Back closes the sheet', !(await sheet.count()))
await hdr.getByRole('button', { name: 'D2C', exact: true }).click(); await waitSettled(page)
const d2cTabs = await hdr.getByRole('tab').allInnerTexts()
check('D2C shows Overall / MyFrido / Mobility sub-tabs', d2cTabs.join('|') === 'Overall|MyFrido|Mobility', d2cTabs.join(', '))
await hdr.getByRole('tab', { name: 'MyFrido' }).click(); await page.waitForTimeout(800)
check('D2C sub-tab goes to MyFrido', page.url().includes('/myfrido'), page.url().replace(/^.*\/sales/, '/sales'))
await hdr.getByRole('button', { name: 'More actions' }).click(); await page.waitForTimeout(400)
const d2cMenu = await page.getByRole('dialog').innerText()
check('D2C "⋯": exports, no Return Analysis on phones', /Day-wise & SKU/.test(d2cMenu) && !/Return Analysis/.test(d2cMenu))
await page.goBack(); await page.waitForTimeout(300)
await page.evaluate(() => { const s = document.querySelector('.page-scroll'); if (s) s.scrollTop = 2000 })
await page.waitForTimeout(300)
const top = await page.evaluate(() => Math.round(document.querySelector('.topnav').getBoundingClientRect().top))
check('header stays pinned after scrolling', top === 0, `top ${top}px`)
const overflow = await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)
check('no horizontal overflow', overflow <= 0, `${overflow}px`)
await page.screenshot({ path: `docs/responsive/after/sales/${ENGINE}-${vp.name}-header.png` }).catch(() => {})
await browser.close()
console.log(fail ? `${ENGINE} ${vp.name}: ${fail} FAILED` : `${ENGINE} ${vp.name}: ALL PASS`)
process.exit(fail ? 1 : 0)
