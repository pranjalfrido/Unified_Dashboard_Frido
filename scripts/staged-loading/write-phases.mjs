#!/usr/bin/env node
// Writes api/_bqPhases.js from a plan.mjs JSON output.
//   node scripts/staged-loading/write-phases.mjs plan.json
import { readFileSync, writeFileSync } from 'fs'
import { join } from 'path'
import { ROOT, CHANNEL_OBJECTS } from './_harness.mjs'

const plan = JSON.parse(readFileSync(process.argv[2], 'utf8'))
const fmtList = arr => '[\n' + chunk(arr.map(x => `'${x}'`), 6).map(c => '      ' + c.join(', ')).join(',\n') + ',\n    ]'
function chunk(a, n) { const o = []; for (let i = 0; i < a.length; i += n) o.push(a.slice(i, i + n)); return o }
const phase = (name, p) => `  ${name}: {\n    queries: ${fmtList(p.queries)},\n    fields: ${fmtList(p.units)},\n  },`

const src = `// Staged-loading phase tables for api/bq.js — GENERATED by scripts/staged-loading/write-phases.mjs
// from measured query→response-field dependencies (scripts/staged-loading/deps.mjs, which skips one
// query at a time against recorded BigQuery results and records which response fields change).
// Regenerate (deps.mjs → plan.mjs → write-phases.mjs) after adding/removing a query or a field.
//
// A "field" is a top-level response key, or channelObject.key for the per-channel objects below.
//   fast          first paint for Overview / Sales / P&L / Ads: KPIs, chMap, daily trends, every
//                 channel's totals/daily/netCalc/prev-period totals, plus <channel>.resolvedAgg — the
//                 small reductions of resolvedDailySKU the KPI tiles / return trends read
//                 (api/_resolvedAgg.js). sales_detail carries <channel>.resolvedAggDetail (per-SKU /
//                 sub-channel / category sums).
//   sales_detail  Sales tabs (+ Overview's category / state / product sections): category, sub-
//                 category, SKU, state, city, region/tier breakdowns.
//   pnl_detail    P&L: SKU-grain cost/SnD rows, pnlSalesRows, category/SKU maps the P&L reads, plus
//                 <channel>.pnlAgg (whole-range reductions) and <channel>.pnlTrend (column-packed
//                 rows for the day-wise trend lines) from api/_pnlAgg.js, instead of the
//                 per-SKU-per-day arrays themselves (PNL_REDUCTIONS_PLAN.md).
//   pnl_margin    Ads' hidden P&L probe: only what each product's CM1 needs on the six P&L tabs Ads
//                 maps to, plus shopify / amzSC / flipkart .pnlAgg.
//   ads_detail    Ads: spend detail, category breakdowns, daily ads/sales by category.
// A field can belong to more than one detail phase (each tab gets everything it reads in one call).
// REDUCED_ONLY fields ship in no phase: their only reader is P&L, through pnlAgg / pnlTrend.
// No phase / an unrecognised phase = the full response, unchanged.

import { computeResolvedAgg, computeCombinedAgg, computeResolvedAggDetail } from './_resolvedAgg.js'
import { computePnlAgg, computePnlTrend, PNL_AGG_CHANNELS } from './_pnlAgg.js'

const TABLE = {
${phase('fast', plan.FAST)}
${phase('sales_detail', plan.sales_detail)}
${phase('pnl_detail', plan.pnl_detail)}
${phase('pnl_margin', plan.pnl_margin)}
${phase('ads_detail', plan.ads_detail)}
}

const REDUCED_ONLY = ${fmtList(plan.reducedOnly).replace(/\n {4}\]$/, '\n]')}

// The per-channel objects whose own keys are phase fields ("shopify.catMap", …).
const CHANNEL_OBJECTS = new Set(${JSON.stringify(CHANNEL_OBJECTS)})

const DETAIL_PHASES = ['sales_detail', 'pnl_detail', 'ads_detail']
const KNOWN_FIELDS = new Set([...Object.values(TABLE).flatMap(t => t.fields), ...REDUCED_ONLY])

const PHASES = {}
for (const [name, t] of Object.entries(TABLE)) {
  PHASES[name] = { name, queries: new Set(t.queries), fields: new Set(t.fields), placeholders: name === 'fast', catchAll: name === 'sales_detail' }
}
// 'slow' (the original detail phase name — nothing calls it any more) = all three detail groups.
PHASES.slow = {
  name: 'slow',
  queries: new Set(DETAIL_PHASES.flatMap(p => TABLE[p].queries)),
  fields: new Set(DETAIL_PHASES.flatMap(p => TABLE[p].fields)),
  placeholders: false, catchAll: true,
}

export const PHASE_NAMES = Object.keys(PHASES)

export function getPhaseDef(phase) {
  return typeof phase === 'string' && Object.prototype.hasOwnProperty.call(PHASES, phase) ? PHASES[phase] : null
}

// Same type, no data — what a field reads as before its phase has arrived.
function emptyLike(v) {
  if (Array.isArray(v)) return []
  if (v === null || v === undefined) return null
  if (typeof v === 'object') return {}
  if (typeof v === 'number') return 0
  if (typeof v === 'string') return ''
  if (typeof v === 'boolean') return false
  return null
}

// Picks a phase's fields out of the full payload. A field no phase lists (added after the tables
// were generated) goes out with sales_detail rather than silently never arriving.
export function pickPhaseFields(payload, def) {
  const owns = f => def.fields.has(f) || (def.catchAll && !KNOWN_FIELDS.has(f))
  const out = {}
  for (const [k, v] of Object.entries(payload)) {
    if (CHANNEL_OBJECTS.has(k) && v && typeof v === 'object' && !Array.isArray(v)) {
      const sub = {}
      let any = false
      for (const [sk, sv] of Object.entries(v)) {
        if (owns(\`\${k}.\${sk}\`)) { sub[sk] = sv; any = true }
        else if (def.placeholders) sub[sk] = emptyLike(sv)
      }
      if (any || def.placeholders) out[k] = sub
    } else if (owns(k)) out[k] = v
    else if (def.placeholders) out[k] = emptyLike(v)
  }
  if (def.name === 'fast') addResolvedAggs(payload, out)
  if (def.name === 'sales_detail' || def.name === 'slow') addResolvedAggDetails(payload, out)
  if (def.name === 'pnl_detail' || def.name === 'slow') addPnl(payload, out, PNL_AGG_CHANNELS, true)
  if (def.name === 'pnl_margin') addPnl(payload, out, ['shopify', 'amzSC', 'flipkart'], false)
  return out
}

// fast: <channel>.resolvedAgg for every channel with resolvedDailySKU rows (+ amzSC.resolvedAgg.plusVC,
// Overview's combined SC+VC Return %). Not part of the full (no-phase) response — the frontend
// computes the same reduction from the rows when it has them (resolvedAggOf).
function addResolvedAggs(payload, out) {
  for (const ch of CHANNEL_OBJECTS) {
    const rows = payload[ch]?.resolvedDailySKU
    if (!Array.isArray(rows) || !out[ch]) continue
    out[ch].resolvedAgg = computeResolvedAgg(rows, { notIntl: ch === 'shopify' })
  }
  if (out.amzSC?.resolvedAgg) out.amzSC.resolvedAgg.plusVC = computeCombinedAgg(payload.amzSC.resolvedDailySKU, payload.amzVC?.resolvedDailySKU)
}

// sales_detail: <channel>.resolvedAggDetail — per-SKU sums (category matrices), Shopify per
// sub-channel (MyFrido / Mobility), Flipkart per category / sub-category (its product filter).
function addResolvedAggDetails(payload, out) {
  for (const ch of CHANNEL_OBJECTS) {
    const rows = payload[ch]?.resolvedDailySKU
    if (!Array.isArray(rows)) continue
    out[ch] = out[ch] || {}
    out[ch].resolvedAggDetail = computeResolvedAggDetail(ch, rows)
  }
}

// pnl_detail / pnl_margin: <channel>.pnlAgg (+ .pnlTrend for pnl_detail), api/_pnlAgg.js. A channel's
// pnlAgg is the same whole object in both phases, so merging either over the other changes nothing.
// Not part of the full (no-phase) response — the frontend computes the same from the rows.
function addPnl(payload, out, channels, withTrend) {
  for (const [ch, agg] of Object.entries(computePnlAgg(payload, channels))) (out[ch] ||= {}).pnlAgg = agg
  if (withTrend) for (const [ch, t] of Object.entries(computePnlTrend(payload))) (out[ch] ||= {}).pnlTrend = t
}
`
writeFileSync(join(ROOT, 'api', '_bqPhases.js'), src)
console.log('wrote api/_bqPhases.js', Object.fromEntries(['FAST', 'sales_detail', 'pnl_detail', 'pnl_margin', 'ads_detail'].map(p => [p, `${plan[p].queries.length}q/${plan[p].units.length}f`])), 'reducedOnly', plan.reducedOnly.length)
